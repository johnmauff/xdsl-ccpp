"""CMake build for the scheme I/O capture test drivers (--capture-test-driver-dir).

The capture pass writes one driver, ``test_<scheme>.F90``, per captured
scheme. This module writes, next to them:

- ``test_<scheme>.cmake`` per scheme: the driver executable (driver, the
  scheme's ``.F90`` and its metadata ``dependencies``) and its ``add_test``;
- ``CMakeLists.txt``: a support library (the generated ``ccpp_kinds.F90``,
  the capture runtime and xdsl_ccpp's framework sources), NetCDF from
  ``nf-config``, options, and an ``include()`` of every fragment.

The scheme sources are written relative to the root of the repository
that holds them (the nearest directory above the first scheme's ``.F90``
with a ``.git``, e.g. an atmospheric_physics checkout), as
``${CCPP_CAPTURE_SCHEME_ROOT}/schemes/kessler/kessler.F90``.
``CCPP_CAPTURE_SCHEME_ROOT`` (``-D`` or the environment; default that
checkout) builds the drivers against another checkout, e.g. a fork with
optimized schemes; the drivers and the support library are unchanged.

Usage::

    cmake -S <driver dir> -B build [-DCCPP_CAPTURE_DIR=<dir with the .nc files>]
    cmake --build build
    ctest --test-dir build

The fragments are per scheme so that several captured schemes collect in
one directory. Each driver is one test, run against the data directory of
the generation that wrote the files (<driver dir>/<label>, where the caps'
ccpp_capture_set_dir sends the run's files); -DCCPP_CAPTURE_DIR points it
at another capture instead.
"""

from __future__ import annotations

import os

from xdsl.utils.hints import isa

from xdsl_ccpp.dialects.ccpp import TablePropertiesOp

_TOP_FILE = "CMakeLists.txt"

# xdsl_ccpp's own Fortran (framework_src/) the drivers link, in dependency
# order: the constituent properties need the hash table, the scheme
# utilities and the constituents' capture need the constituent properties.
_FRAMEWORK_SRC_DIR = os.path.join(
    os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "framework_src"
)
_SUPPORT_FILES = (
    "ccpp_hashable.F90",
    "ccpp_hash_table.F90",
    "ccpp_constituent_prop_mod.F90",
    "ccpp_scheme_utils.F90",
    "ccpp_capture_mod.F90",
    "ccpp_capture_constituents_mod.F90",
)

_TOP_TEMPLATE = """\
# Generated by xdsl_ccpp (--capture-test-driver-dir); regenerated with the
# caps. Builds the scheme I/O capture test drivers in this directory (one
# test_<scheme>.cmake each) and runs them against captured NetCDF files:
#
#   cmake -S <this dir> -B build
#   cmake --build build
#   ctest --test-dir build --output-on-failure
#
# Each driver is one test, run against the captures of the generation that
# wrote this file:
#   {data_dir}
# -DCCPP_CAPTURE_DIR=<dir> runs them against another capture instead.
#
# Needs a Fortran compiler and netcdf-fortran built with it (nf-config on
# PATH, or -DNF_CONFIG=...). -DOPENACC=ON builds with OpenACC
# (CCPP_CAPTURE_ACC_FLAGS, default -acc; with nvfortran
# -gpu=nofma,math_uniform is added) for GPU replay of the same captures:
# the drivers always carry their own enter/exit data directives (comments
# in a CPU build). With nvfortran a CPU build gets -noacc -- nvfortran
# otherwise compiles a scheme's !$acc directives and the "CPU" replay runs
# them on the GPU -- and every build gets -Mnofma, as CAM-SIMA's nvhpc
# builds do, so a replay can match a capture bit for bit.
# CCPP_CAPTURE_TOLERANCE in the environment overrides the drivers'
# real-valued tolerance at run time.
#
# The test_<scheme>.cmake files name the scheme sources under
# CCPP_CAPTURE_SCHEME_ROOT, by default the checkout they were generated from.
# To test another checkout (e.g. a fork with optimized schemes) against the
# same captures, set CCPP_CAPTURE_SCHEME_ROOT (-D, or the environment when
# CMake first configures) to its top-level directory.
cmake_minimum_required(VERSION 3.19)
project(ccpp_capture_tests LANGUAGES Fortran)

set(CCPP_CAPTURE_DIR "" CACHE PATH
    "Directory of the captures to test (default: those of the generation that wrote this file)")
if(NOT CCPP_CAPTURE_DIR)
  set(CCPP_CAPTURE_DIR {data_dir_arg})
endif()
option(OPENACC "Build the drivers with OpenACC (GPU replay)" OFF)
set(CCPP_CAPTURE_ACC_FLAGS "-acc" CACHE STRING "OpenACC compile and link flags")
set(CCPP_CAPTURE_EXTRA_SOURCES "" CACHE STRING
    "Further Fortran sources the schemes use (;-separated absolute paths)")

find_program(NF_CONFIG nf-config REQUIRED)
execute_process(COMMAND ${{NF_CONFIG}} --fflags OUTPUT_VARIABLE _nf_fflags
                OUTPUT_STRIP_TRAILING_WHITESPACE COMMAND_ERROR_IS_FATAL ANY)
execute_process(COMMAND ${{NF_CONFIG}} --flibs OUTPUT_VARIABLE _nf_flibs
                OUTPUT_STRIP_TRAILING_WHITESPACE COMMAND_ERROR_IS_FATAL ANY)
separate_arguments(_nf_fflags UNIX_COMMAND "${{_nf_fflags}}")
separate_arguments(_nf_flibs UNIX_COMMAND "${{_nf_flibs}}")

# Generated drivers have long lines.
if(CMAKE_Fortran_COMPILER_ID STREQUAL "GNU")
  add_compile_options(-ffree-line-length-none)
endif()
if(CMAKE_Fortran_COMPILER_ID STREQUAL "NVHPC")
  add_compile_options(-Mnofma)
endif()
if(OPENACC)
  separate_arguments(_acc_flags UNIX_COMMAND "${{CCPP_CAPTURE_ACC_FLAGS}}")
  if(CMAKE_Fortran_COMPILER_ID STREQUAL "NVHPC")
    list(APPEND _acc_flags -gpu=nofma,math_uniform)
  endif()
  add_compile_options(${{_acc_flags}})
  add_link_options(${{_acc_flags}})
elseif(CMAKE_Fortran_COMPILER_ID STREQUAL "NVHPC")
  add_compile_options(-noacc)
  add_link_options(-noacc)
endif()

if(DEFINED ENV{{CCPP_CAPTURE_SCHEME_ROOT}})
  set(_ccpp_capture_scheme_root "$ENV{{CCPP_CAPTURE_SCHEME_ROOT}}")
else()
  set(_ccpp_capture_scheme_root {scheme_root_arg})
endif()
set(CCPP_CAPTURE_SCHEME_ROOT "${{_ccpp_capture_scheme_root}}" CACHE PATH
    "Top-level directory of the scheme sources (default: the generating checkout)")
message(STATUS "Scheme sources from ${{CCPP_CAPTURE_SCHEME_ROOT}}")

add_library(ccpp_capture_support STATIC
{support_sources}
  ${{CCPP_CAPTURE_EXTRA_SOURCES}})
set_target_properties(ccpp_capture_support PROPERTIES
  Fortran_MODULE_DIRECTORY ${{CMAKE_BINARY_DIR}}/mod/ccpp_capture_support)
target_include_directories(ccpp_capture_support PUBLIC
  ${{CMAKE_BINARY_DIR}}/mod/ccpp_capture_support)
target_compile_options(ccpp_capture_support PUBLIC ${{_nf_fflags}})
target_link_libraries(ccpp_capture_support PUBLIC ${{_nf_flibs}})

enable_testing()

file(GLOB _ccpp_capture_tests CONFIGURE_DEPENDS "${{CMAKE_CURRENT_SOURCE_DIR}}/test_*.cmake")
foreach(_test IN LISTS _ccpp_capture_tests)
  include(${{_test}})
endforeach()
"""

_FRAGMENT_TEMPLATE = """\
# Generated by xdsl_ccpp (--capture-test-driver-dir): the test driver for
# scheme {scheme}; included by CMakeLists.txt in this directory.
add_executable(test_{scheme}
  ${{CMAKE_CURRENT_LIST_DIR}}/test_{scheme}.F90
{sources})
set_target_properties(test_{scheme} PROPERTIES
  Fortran_MODULE_DIRECTORY ${{CMAKE_BINARY_DIR}}/mod/test_{scheme})
target_link_libraries(test_{scheme} PRIVATE ccpp_capture_support)
add_test(NAME test_{scheme} COMMAND test_{scheme} WORKING_DIRECTORY "${{CCPP_CAPTURE_DIR}}")
"""


def _cmake_path(path: str) -> str:
    """A path as a quoted CMake argument."""
    return '"' + os.path.abspath(path).replace("\\", "/").replace('"', '\\"') + '"'


def _source_lines(paths) -> str:
    return "\n".join(f"  {_cmake_path(p)}" for p in paths)


def _scheme_source_lines(paths, scheme_root) -> str:
    """*paths* as CMake arguments, those under *scheme_root* as
    "${CCPP_CAPTURE_SCHEME_ROOT}/<relative path>"."""
    lines = []
    for path in paths:
        path = os.path.abspath(path)
        if scheme_root and path.startswith(scheme_root + os.sep):
            rel = os.path.relpath(path, scheme_root).replace("\\", "/")
            lines.append(f'  "${{CCPP_CAPTURE_SCHEME_ROOT}}/{rel}"')
        else:
            lines.append(f"  {_cmake_path(path)}")
    return "\n".join(lines)


def scheme_source_root(path: str) -> "str | None":
    """The nearest directory above *path* holding a ``.git`` (directory, or
    file for a submodule), or None."""
    directory = os.path.dirname(os.path.abspath(path))
    while True:
        if os.path.exists(os.path.join(directory, ".git")):
            return directory
        parent = os.path.dirname(directory)
        if parent == directory:
            return None
        directory = parent


def render_capture_cmakelists(support_sources, data_dir: str,
                              scheme_root: "str | None" = None) -> str:
    """CMakeLists.txt text: support library from *support_sources* (in
    compile order), NetCDF, options, the default capture directory
    *data_dir*, the default CCPP_CAPTURE_SCHEME_ROOT *scheme_root*, include
    of every test fragment."""
    return _TOP_TEMPLATE.format(
        support_sources=_source_lines(support_sources),
        data_dir=os.path.abspath(data_dir),
        data_dir_arg=_cmake_path(data_dir),
        scheme_root_arg=_cmake_path(scheme_root) if scheme_root else '""',
    )


def render_capture_fragment(scheme: str, sources,
                            scheme_root: "str | None" = None) -> str:
    """test_<scheme>.cmake text: the driver plus *sources* (the scheme's
    .F90 and its dependencies), those under *scheme_root* relative to
    CCPP_CAPTURE_SCHEME_ROOT."""
    return _FRAGMENT_TEMPLATE.format(
        scheme=scheme, sources=_scheme_source_lines(sources, scheme_root))


def scheme_meta_files(meta_paths) -> dict:
    """{scheme name: .meta path} from the `name` of each
    [ccpp-table-properties] section with `type = scheme`."""
    result: dict = {}
    for meta_path in meta_paths:
        # Section state: inside a scheme's [ccpp-table-properties]?
        in_properties = False
        name = None
        with open(meta_path) as f:
            lines = [raw.split("#", 1)[0].strip() for raw in f]
        for line in lines + ["["]:  # a final "[" closes the last section
            if line.startswith("["):
                if in_properties and name:
                    result.setdefault(name, meta_path)
                in_properties = line.lower() == "[ccpp-table-properties]"
                name = None
                continue
            if not in_properties or "=" not in line:
                continue
            key, value = (part.strip() for part in line.split("=", 1))
            if key.lower() == "name":
                name = value
            elif key.lower() == "type" and value.lower() != "scheme":
                in_properties = False
    return result


def scheme_dependencies(module, scheme: str) -> list:
    """Absolute paths of the `dependencies` of *scheme*'s table properties in
    the frontend *module* (each joined with its `dependencies_path`, which
    the frontend sets to the .meta file's directory by default)."""
    deps: list = []
    for op in module.walk():
        if not isa(op, TablePropertiesOp):
            continue
        if op.table_type.data != "scheme" or op.table_name.data != scheme:
            continue
        deps_attr = op.attributes.get("dependencies")
        if deps_attr is None:
            continue
        dep_dir_attr = op.attributes.get("dependencies_path")
        dep_dir = dep_dir_attr.data if dep_dir_attr is not None else ""
        for dep in deps_attr.data:
            path = os.path.join(dep_dir, dep.data) if dep_dir else dep.data
            if path not in deps:
                deps.append(path)
    return deps


def support_sources(kinds_path: str) -> list:
    """The support library's sources: the generated ccpp_kinds.F90 and
    xdsl_ccpp's framework and capture runtime files."""
    return [kinds_path] + [os.path.join(_FRAMEWORK_SRC_DIR, name) for name in _SUPPORT_FILES]


def write_capture_cmake(driver_dir: str, scheme_sources: dict, support_sources,
                        data_dir: str) -> list:
    """Write test_<scheme>.cmake for every {scheme: [sources]} entry and the
    CMakeLists.txt, whose tests run against *data_dir*; return the paths
    written. The scheme sources are named relative to the repository root
    of the first scheme's source (scheme_source_root)."""
    os.makedirs(driver_dir, exist_ok=True)
    first = next((srcs[0] for srcs in scheme_sources.values() if srcs), None)
    scheme_root = scheme_source_root(first) if first else None
    written = []
    for scheme, sources in scheme_sources.items():
        path = os.path.join(driver_dir, f"test_{scheme}.cmake")
        with open(path, "w") as f:
            f.write(render_capture_fragment(scheme, sources, scheme_root))
        written.append(path)
    path = os.path.join(driver_dir, _TOP_FILE)
    with open(path, "w") as f:
        f.write(render_capture_cmakelists(support_sources, data_dir, scheme_root))
    written.append(path)
    return written
