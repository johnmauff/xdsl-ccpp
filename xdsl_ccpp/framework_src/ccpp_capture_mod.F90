! Runtime support for xdsl_ccpp's opt-in --capture-scheme feature
! (scheme_io_capture_pass.py). Not part of any CCPP scheme's own interface
! -- linked in only when a build enables --capture-scheme at cap-generation
! time. Writes a scheme's input/output arguments to NetCDF files for
! building data-driven, scheme-level regression tests, and reads them back
! (ccpp_capture_open_call/ccpp_capture_read) in a generated standalone
! test-driver program, which checks the scheme's outputs with
! ccpp_capture_compare.
!
! Generated by a template script from uniform per-(type, rank) procedures;
! edit all of a family together.
!
! File layout (scheme-io-capture-netcdf): one NetCDF-4 file per scheme call,
! <CCPP_CAPTURE_DIR>/<table>_<n>.nc, where <table> is the scheme's
! subroutine (e.g. kessler_run) and <n> counts that table's calls in this
! process (1, 2, ...). The directory is CCPP_CAPTURE_DIR when set in the
! environment, else the one given to ccpp_capture_set_dir (the generator's
! --capture-test-driver-dir, so data and test drivers share a directory),
! else the working directory.
! Global attributes: ccpp_table, ccpp_call, ccpp_capture_format_version.
! Group `in` holds the arguments as passed (intent in and inout, written
! before the call), group `out` the results (intent out and inout, written
! after it). Each variable has attributes ccpp_type (integer, logical,
! real, character), and standard_name/units when given. Dimensions are
! named from the argument's metadata dimensions (dim_names,
! comma-separated); a name met again with another length gets a suffix
! (_2, _3, ...); a missing name becomes <variable>_dim<i>. Logicals are
! stored as bytes (0/1), characters as char arrays with a leading
! <variable>_len dimension (a zero-length string is left unwritten: fill).
!
! Writing: ccpp_capture_begin(table, 'before') creates the call's file and
! makes `in` current; ccpp_capture(name, value, ...) writes one variable;
! ccpp_capture_end() closes the file. ccpp_capture_begin(table, 'after')
! reopens the same call's file with `out` current. One file is open at a
! time. A failure is reported to stderr and the capture skipped -- a
! simulation never aborts because a capture could not be written.
!
! MPI: none here. scheme_io_capture_pass.py guards every capture call with
! the host's mpi-root flag (CAM-SIMA's masterproc) when the host declares
! one, so one task writes.
!
! ccpp_capture_tolerance_override: a generated driver bakes a default
! tolerance into its source; CCPP_CAPTURE_TOLERANCE (a real number)
! overrides it at run time, so one compiled driver can be rerun against
! several tolerances (cross-compiler or GPU comparisons).
module ccpp_capture_mod

  use ccpp_kinds, only: kind_phys
  use netcdf

  implicit none
  private

