  ! ---------------------------------------------------------------------
  ! Compare procedures -- one per (type, rank). Integer, logical and
  ! character compares are exact; real compares take an absolute
  ! tolerance. All return .true. when every element matches. Array
  ! variants optionally report the 1-based linear (column-major) index of
  ! the first mismatch (0 when all match); real arrays also report the
  ! maximum and mean absolute difference over every element.
  ! ---------------------------------------------------------------------


  function ccpp_capture_compare_int_0d(actual, expected) result(ok)
    integer, intent(in) :: actual, expected
    logical :: ok
    ok = (actual == expected)
  end function ccpp_capture_compare_int_0d

  function ccpp_capture_compare_int_1d(actual, expected, first_mismatch_index) result(ok)
    integer, intent(in) :: actual(:), expected(:)
    integer, optional, intent(out) :: first_mismatch_index
    logical :: ok
    logical :: mismatch(size(actual))
    mismatch = (actual /= expected)
    ok = .not. any(mismatch)
    if (present(first_mismatch_index)) then
      if (ok) then
        first_mismatch_index = 0
      else
        first_mismatch_index = first_true_index(reshape(mismatch, [size(mismatch)]))
      end if
    end if
  end function ccpp_capture_compare_int_1d

  function ccpp_capture_compare_int_2d(actual, expected, first_mismatch_index) result(ok)
    integer, intent(in) :: actual(:,:), expected(:,:)
    integer, optional, intent(out) :: first_mismatch_index
    logical :: ok
    logical :: mismatch(size(actual,1), size(actual,2))
    mismatch = (actual /= expected)
    ok = .not. any(mismatch)
    if (present(first_mismatch_index)) then
      if (ok) then
