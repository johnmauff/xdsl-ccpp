  integer, parameter :: ccpp_capture_format_version = 2

  ! Per-table call counters -- fixed capacity, no reallocation.
  integer, parameter :: ccpp_capture_max_tables = 256
  character(len=256), save :: lc_tables(ccpp_capture_max_tables) = ''
  integer,            save :: lc_counts(ccpp_capture_max_tables) = 0
  integer,            save :: lc_ntables = 0

  ! The open file (-1: none) and the group being written or read.
  integer, save :: lc_ncid = -1
  integer, save :: lc_grpid = -1
  character(len=1024), save :: lc_path = ''

  ! Capture directory when CCPP_CAPTURE_DIR is unset ('' = working dir).
  character(len=1024), save :: lc_default_dir = ''

  integer :: lc_no_shape(0)

contains

  ! ---------------------------------------------------------------------
  ! Internal helpers
  ! ---------------------------------------------------------------------

  ! Reports a NetCDF error to stderr; returns .true. on success.
  logical function lc_check(status, what, name)
    integer, intent(in) :: status
    character(len=*), intent(in) :: what, name

    lc_check = (status == NF90_NOERR)
    if (.not. lc_check) then
      write(0,*) 'ccpp_capture_mod: ', what, ' failed for ', trim(name), &
                 ' (', trim(lc_path), '): ', trim(nf90_strerror(status))
    end if
  end function lc_check

  ! NF90_DOUBLE for 8-byte kind_phys, NF90_FLOAT otherwise.
  integer function lc_real_xtype()
    if (precision(1.0_kind_phys) > 7) then
      lc_real_xtype = NF90_DOUBLE
    else
      lc_real_xtype = NF90_FLOAT
    end if
  end function lc_real_xtype

  ! Next (increment) or current (peek) 1-based call number of `table`;
  ! -1 if the table of counters is full.
  integer function lc_call_number(table, increment)
    character(len=*), intent(in) :: table
    logical, intent(in) :: increment
    integer :: i

    do i = 1, lc_ntables
      if (trim(lc_tables(i)) == trim(table)) then
        if (increment) lc_counts(i) = lc_counts(i) + 1
        lc_call_number = lc_counts(i)
        return
      end if
    end do
    if (.not. increment) then
      lc_call_number = 0
      return
    end if
    if (lc_ntables >= ccpp_capture_max_tables) then
      write(0,*) 'ccpp_capture_mod: too many captured tables; skipping ', trim(table)
      lc_call_number = -1
      return
    end if
    lc_ntables = lc_ntables + 1
    lc_tables(lc_ntables) = table
    lc_counts(lc_ntables) = 1
    lc_call_number = 1
  end function lc_call_number

  ! <capture directory>/<table>_<n>.nc (see the header)
  function lc_file_path(table, n) result(path)
    character(len=*), intent(in) :: table
    integer, intent(in) :: n
    character(len=:), allocatable :: path
    character(len=1024) :: dir
    character(len=12) :: num
    integer :: dir_len, status

    call get_environment_variable('CCPP_CAPTURE_DIR', dir, dir_len, status)
    if (status /= 0 .or. dir_len == 0) then
      dir = lc_default_dir
      dir_len = len_trim(dir)
    end if
    write(num, '(I0)') n
    if (dir_len > 0) then
      path = trim(dir) // '/' // trim(table) // '_' // trim(num) // '.nc'
    else
      path = trim(table) // '_' // trim(num) // '.nc'
    end if
  end function lc_file_path

  ! The i-th comma-separated entry of dim_names, or <var>_dim<i>.
  function lc_dim_name(dim_names, i, var) result(dname)
    character(len=*), optional, intent(in) :: dim_names
    integer, intent(in) :: i
    character(len=*), intent(in) :: var
    character(len=:), allocatable :: dname
    integer :: k, first, comma
    character(len=12) :: num

    dname = ''
    if (present(dim_names)) then
      first = 1
      do k = 1, i
        comma = index(dim_names(first:), ',')
        if (k == i) then
          if (comma == 0) then
            dname = trim(adjustl(dim_names(first:)))
          else
            dname = trim(adjustl(dim_names(first:first + comma - 2)))
          end if
        else if (comma == 0) then
          exit
        else
          first = first + comma
        end if
      end do
    end if
    if (len(dname) == 0) then
      write(num, '(I0)') i
      dname = trim(var) // '_dim' // trim(num)
    end if
  end function lc_dim_name

  ! A dimension of the open file named `dname` (or dname_2, dname_3, ...
  ! when that name already has another length) with this length; -1 on
  ! failure.
  integer function lc_dim(dname, length)
    character(len=*), intent(in) :: dname
    integer, intent(in) :: length
    character(len=256) :: try
    integer :: k, status, dimid, dlen

    lc_dim = -1
    do k = 1, 99
      if (k == 1) then
        try = dname
      else
        write(try, '(A,"_",I0)') trim(dname), k
      end if
      status = nf90_inq_dimid(lc_ncid, trim(try), dimid)
      if (status /= NF90_NOERR) then
        if (lc_check(nf90_def_dim(lc_ncid, trim(try), length, dimid), 'define dimension', try)) then
          lc_dim = dimid
        end if
        return
      end if
      if (.not. lc_check(nf90_inquire_dimension(lc_ncid, dimid, len=dlen), &
                         'inquire dimension', try)) return
      if (dlen == length) then
        lc_dim = dimid
        return
      end if
    end do
  end function lc_dim

  ! Defines variable `name` in the current group with the given shape
  ! (Fortran order) and attributes; returns its id, or -1 when nothing is
  ! open or a step fails.
  integer function lc_def_var(name, xtype, shp, ccpp_type, standard_name, units, dim_names)
    character(len=*), intent(in) :: name
    integer, intent(in) :: xtype
    integer, intent(in) :: shp(:)
    character(len=*), intent(in) :: ccpp_type
    character(len=*), optional, intent(in) :: standard_name, units, dim_names
    integer :: dimids(size(shp)), i, varid

    lc_def_var = -1
    if (lc_ncid < 0 .or. lc_grpid < 0) return
    do i = 1, size(shp)
      dimids(i) = lc_dim(lc_dim_name(dim_names, i, name), shp(i))
      if (dimids(i) < 0) return
    end do
    if (size(shp) == 0) then
      if (.not. lc_check(nf90_def_var(lc_grpid, name, xtype, varid), 'define', name)) return
    else
      if (.not. lc_check(nf90_def_var(lc_grpid, name, xtype, dimids, varid), 'define', name)) return
      if (.not. lc_check(nf90_def_var_deflate(lc_grpid, varid, 1, 1, 1), 'compress', name)) return
    end if
    if (.not. lc_check(nf90_put_att(lc_grpid, varid, 'ccpp_type', ccpp_type), 'attribute', name)) return
    if (present(standard_name)) then
      if (len_trim(standard_name) > 0) then
        if (.not. lc_check(nf90_put_att(lc_grpid, varid, 'standard_name', trim(standard_name)), &
                           'attribute', name)) return
      end if
    end if
    if (present(units)) then
      if (len_trim(units) > 0) then
        if (.not. lc_check(nf90_put_att(lc_grpid, varid, 'units', trim(units)), 'attribute', name)) return
      end if
    end if
    lc_def_var = varid
  end function lc_def_var

  ! Finds variable `name` in `group` of the open file and checks its shape
  ! against shp (Fortran order), skipping the first `skip` file dimensions
  ! (a character variable's length). Reports a problem unless the caller
  ! passed `found` (then a missing variable is a quiet .false.).
  logical function lc_find_var(group, name, shp, skip, grpid, varid, found)
    character(len=*), intent(in) :: group, name
    integer, intent(in) :: shp(:)
    integer, intent(in) :: skip
    integer, intent(out) :: grpid, varid
    logical, optional, intent(out) :: found
    integer :: ndims, i, dlen
    integer :: dimids(NF90_MAX_VAR_DIMS)

    lc_find_var = .false.
    if (present(found)) found = .false.
    if (lc_ncid < 0) then
      if (.not. present(found)) write(0,*) 'ccpp_capture_mod: no capture file open reading ', trim(name)
      return
    end if
    if (nf90_inq_ncid(lc_ncid, group, grpid) /= NF90_NOERR .or. &
        nf90_inq_varid(grpid, name, varid) /= NF90_NOERR) then
      if (.not. present(found)) then
        write(0,*) 'ccpp_capture_mod: no variable ', trim(group), '/', trim(name), ' in ', trim(lc_path)
      end if
      return
    end if
    if (.not. lc_check(nf90_inquire_variable(grpid, varid, ndims=ndims, dimids=dimids), &
                       'inquire', name)) return
    if (ndims - skip /= size(shp)) then
      write(0,*) 'ccpp_capture_mod: rank mismatch reading ', trim(group), '/', trim(name)
      return
    end if
    do i = 1, size(shp)
      if (.not. lc_check(nf90_inquire_dimension(lc_ncid, dimids(skip + i), len=dlen), &
                         'inquire dimension', name)) return
      if (dlen /= shp(i)) then
        write(0,*) 'ccpp_capture_mod: shape mismatch reading ', trim(group), '/', trim(name)
        return
      end if
    end do
    lc_find_var = .true.
  end function lc_find_var

  ! ---------------------------------------------------------------------
  ! Writing
  ! ---------------------------------------------------------------------

  ! Directory for the capture files when CCPP_CAPTURE_DIR is unset. The
  ! generated caps call this before each capture with the generator's
  ! --capture-test-driver-dir.
  subroutine ccpp_capture_set_dir(dir)
    character(len=*), intent(in) :: dir
    lc_default_dir = dir
  end subroutine ccpp_capture_set_dir

  ! timing 'before': create the next call's file for `table`, `in` current.
  ! timing 'after': reopen the current call's file, `out` current.
  subroutine ccpp_capture_begin(table, timing)
    character(len=*), intent(in) :: table, timing
    integer :: n, grp_out
    logical :: ok

    if (lc_ncid >= 0) call ccpp_capture_end()
    if (timing == 'before') then
      n = lc_call_number(table, .true.)
      if (n < 0) return
      lc_path = lc_file_path(table, n)
      if (.not. lc_check(nf90_create(trim(lc_path), ior(NF90_CLOBBER, NF90_NETCDF4), lc_ncid), &
                         'create', table)) then
        lc_ncid = -1
        return
      end if
      ok = lc_check(nf90_put_att(lc_ncid, NF90_GLOBAL, 'ccpp_table', table), 'attribute', table)
      if (ok) ok = lc_check(nf90_put_att(lc_ncid, NF90_GLOBAL, 'ccpp_call', n), 'attribute', table)
      if (ok) ok = lc_check(nf90_put_att(lc_ncid, NF90_GLOBAL, 'ccpp_capture_format_version', &
                                         ccpp_capture_format_version), 'attribute', table)
      if (ok) ok = lc_check(nf90_def_grp(lc_ncid, 'out', grp_out), 'define group out', table)
      if (ok) ok = lc_check(nf90_def_grp(lc_ncid, 'in', lc_grpid), 'define group in', table)
      if (.not. ok) call ccpp_capture_end()
    else
      n = lc_call_number(table, .false.)
      if (n <= 0) return
      lc_path = lc_file_path(table, n)
      if (.not. lc_check(nf90_open(trim(lc_path), NF90_WRITE, lc_ncid), 'reopen', table)) then
        lc_ncid = -1
        return
      end if
      if (.not. lc_check(nf90_inq_ncid(lc_ncid, 'out', lc_grpid), 'find group out', table)) then
        call ccpp_capture_end()
      end if
    end if
  end subroutine ccpp_capture_begin

  ! Closes the file being written (no-op when none is open).
  subroutine ccpp_capture_end()
    if (lc_ncid >= 0) then
      if (lc_check(nf90_close(lc_ncid), 'close', lc_path)) continue
    end if
    lc_ncid = -1
    lc_grpid = -1
  end subroutine ccpp_capture_end


  subroutine ccpp_capture_int_0d(name, value, standard_name, units, dim_names)
    character(len=*), intent(in) :: name
